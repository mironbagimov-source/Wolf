#pragma once

#include <cstdint>
#include <cstddef>

// Точка стыковки со скриптовой машиной Unreal Engine 3.
//
// Весь UnrealScript исполняется движком через несколько функций UObject, и
// перехват нужной даёт поток всех игровых событий: спавн, смерть, обнаружение,
// применение способности, разговор. На этом строится всё, что нельзя сделать
// конфигом.
//
// Какая именно функция нужна — вопрос, который нельзя решить чтением
// исходников UE3: Arkane правили движок, имена в релизе вырезаны, а функции с
// похожими прологами стоят рядом. Поэтому здесь описаны обе, между которыми
// шёл выбор, и плагин ставит счётчики на каждую, чтобы ответила сама игра.
//
// Все они — методы класса, то есть __thiscall: указатель на объект приезжает в
// ECX. Отдельного соглашения __thiscall для свободных функций в C++ нет,
// поэтому перехватчики объявляются как __fastcall — оно берёт первый аргумент
// из ECX, второй из EDX. Параметр edx не используется и существует только
// чтобы разложить регистры правильно.
//
// Число аргументов обязано совпадать с оригиналом до штуки. Функции чистят
// стек сами (ret $N), поэтому лишний переданный аргумент — это разъехавшийся
// стек и падение в случайном месте много позже.

namespace dmk {
namespace ue3 {

// Типы движка оставлены непрозрачными сознательно. Настоящая раскладка UObject
// у каждой игры своя, и объявить её можно только по дампу SDK с конкретного
// билда. Пока дампа нет, честнее работать с адресами, чем с выдуманными
// полями, которые скомпилируются и молча прочитают мусор.
using UObject = void;
using UFunction = void;
using FFrame = void;

// void UObject::CallFunction(FFrame& Stack, void* Result, UFunction* Function)
//
// Вызывается на каждый вызов скриптовой функции из байткода. Ценна тем, что
// описание функции приходит явным аргументом — значит имя события можно
// прочитать сразу, не разбирая кадр стека.
using CallFunctionFn = void(__fastcall*)(UObject* self,
                                         void* edx,
                                         FFrame* stack,
                                         void* result,
                                         UFunction* function);

// void UObject::<обработчик опкода>(FFrame& Stack, void* Result)
//
// Часть скриптовой машины: разбирает операнды прямо из байткода и уходит в
// ProcessInternal. Описания функции у неё в аргументах нет, поэтому как
// источник имён она не годится — но как счётчик показывает, идёт ли вообще
// исполнение скриптов.
using OpcodeHandlerFn = void(__fastcall*)(UObject* self,
                                          void* edx,
                                          FFrame* stack,
                                          void* result);

// Один перехватываемый адрес: как его найти и что с ним делать.
struct ProbeBinding {
    // Сигнатура в виде "55 8B EC ?? ?? 83 EC".
    char pattern[256] = {0};

    // Длина пролога в байтах, кратная целым инструкциям. Смотрится в
    // дизассемблере, см. комментарий в detour.h.
    std::size_t prologue = 0;

    // Результат поиска, заполняется в рантайме.
    std::uintptr_t address = 0;
};

struct Bindings {
    ProbeBinding callFunction;
    ProbeBinding opcodeHandler;

    // Разрешено ли ставить хуки.
    bool hookEnabled = false;
};

}  // namespace ue3
}  // namespace dmk
