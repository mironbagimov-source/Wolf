#pragma once

#include <cstdint>
#include <cstddef>

// Точка стыковки с объектной системой Unreal Engine 3.
//
// Весь UnrealScript исполняется через UObject::ProcessEvent — движок дергает
// её на каждый вызов скриптовой функции, передавая объект, описание функции и
// упакованные аргументы. Один перехват этой функции даёт поток всех игровых
// событий: спавн, смерть, обнаружение, применение способности. На этом и
// строится всё, что нельзя сделать конфигом.
//
// Сигнатура в исходниках UE3 такая:
//
//     void UObject::ProcessEvent(UFunction* Function, void* Parms, void* Result);
//
// Это метод класса, то есть __thiscall: указатель на объект приезжает в ECX.
// Отдельного соглашения __thiscall для свободных функций в C++ нет, поэтому
// перехватчик объявляется как __fastcall — оно берёт первый аргумент из ECX,
// второй из EDX. Второй параметр (edx) не используется и существует только
// чтобы разложить регистры правильно.

namespace dmk {
namespace ue3 {

// Типы движка оставлены непрозрачными сознательно. Настоящая раскладка UObject
// у каждой игры своя (Arkane правили движок), и объявить её можно только по
// дампу SDK с конкретного билда. Пока дампа нет, честнее работать с адресами,
// чем с выдуманными полями, которые скомпилируются и молча прочитают мусор.
using UObject = void;
using UFunction = void;

using ProcessEventFn = void(__fastcall*)(UObject* self,
                                         void* edx,
                                         UFunction* function,
                                         void* parms,
                                         void* result);

// Адреса и смещения, снятые с конкретного билда игры. Заполняются не из кода,
// а из native.ini рядом с DLL: подбор сигнатуры — итеративная работа, и
// пересобирать DLL на каждую попытку незачем.
struct Bindings {
    // Сигнатура ProcessEvent в виде "55 8B EC ?? ?? 83 EC".
    char processEventPattern[256] = {0};

    // Длина пролога ProcessEvent в байтах, кратная целым инструкциям.
    // Смотрится в дизассемблере, см. комментарий в detour.h.
    std::size_t processEventPrologue = 0;

    // Разрешено ли ставить хук. Пока сигнатура не подобрана, слой должен
    // загружаться и писать лог, но в чужой код не лезть.
    bool hookEnabled = false;

    // Результат поиска, заполняется в рантайме.
    std::uintptr_t processEventAddress = 0;
};

}  // namespace ue3
}  // namespace dmk
