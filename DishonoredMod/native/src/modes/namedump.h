#pragma once

#include <string>

#include "../mode.h"

// Выгрузка всей таблицы имён игры.
//
// Словарь, снятый из потока событий, показывает только то, что успело
// вызваться: два сеанса подряд дали 271 и 270 имён, и разговоров среди них не
// оказалось ни разу. Ждать, пока нужное событие само пройдёт через хук, — это
// заход в игру за попытку, и каждый может кончиться ничем.
//
// GNames устроена иначе. Туда попадает имя всего, что игра вообще загрузила:
// каждый класс, каждая функция, каждое свойство, вне зависимости от того,
// исполнялось оно или нет. Один проход по таблице даёт то же, что дало бы
// чтение пакетов игры, — только пакеты сжаты и весят гигабайты, а таблица уже
// разобрана и лежит в памяти.
//
// Отсюда же берутся имена, которых иначе не найти: события разговора, состояния
// смерти, названия способностей.

namespace dmk {

class NameDumpMode final : public IGameMode {
public:
    const char* id() const override { return "namedump"; }

    void onEnable() override;
    void onDisable() override;

    bool onProcessEvent(ue3::UObject* self,
                        ue3::UFunction* function,
                        void* parms) override;

private:
    // Таблица заполняется по мере загрузки уровня, поэтому снимать её сразу
    // при включении режима рано: на старте там будут имена движка, но не карты.
    // Ждём, пока рост прекратится.
    static constexpr unsigned long long kSettleEvents = 200000;

    // Ниже этого порога снимать нечего: уровень ещё не загружен, и в памяти
    // только объекты движка.
    static constexpr unsigned long long kMinEventsToDump = 5000;

    bool done_ = false;
    unsigned long long events_ = 0;

    void dump();
};

}  // namespace dmk
