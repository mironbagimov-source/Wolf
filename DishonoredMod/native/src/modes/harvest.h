#pragma once

#include <atomic>
#include <cstdint>
#include <string>

#include "../mode.h"

// Полный сбор данных за один заход в игру.
//
// Причина появления. Прежние режимы задавали игре по одному вопросу за запуск:
// namedump снимал имена, objdump обходил объекты, каждый следующий вопрос стоил
// ещё одного прохождения. Данные копились, полигры ушло на спидран ради них, а
// список вопросов не кончался. Так работать нельзя: цена ошибки в моей сборке —
// не пересборка, а чужой вечер.
//
// Отсюда устройство. Режим не выбирает, что снять, — он снимает всё сразу:
// таблицу имён, глобальный список объектов, каталог классов и сырую память
// интересных объектов. Последнее важнее всего: имея байты объекта, смещения
// полей подбираются потом, без игры, и следующего захода не требуют.
//
// Три защиты от неудачного момента:
//
//   1. Горячая клавиша. Снимок делается тогда, когда игрок стоит там, где надо,
//      а не когда счётчик событий дорос до порога. Нажимать можно сколько
//      угодно раз — файлы нумеруются.
//   2. Пороги. Если про клавишу забыли, снимки идут сами: после загрузки
//      уровня, потом ещё дважды по мере игры.
//   3. Запасной список. Глобальный массив объектов ищется перебором памяти и
//      может не найтись. Поэтому режим независимо копит указатели на объекты
//      прямо из потока событий: даже если перебор провалится, снимать будет
//      что.
//
// Отказ любой части не отменяет остальные: файл пишется всегда, и в нём
// сказано, что удалось, а что нет.

namespace dmk {

class HarvestMode final : public IGameMode {
public:
    const char* id() const override { return "harvest"; }

    void onEnable() override;
    void onDisable() override;

    bool onProcessEvent(ue3::UObject* self,
                        ue3::UFunction* function,
                        void* parms) override;

private:
    // Пороги автоснимков.
    //
    // Считаются в событиях, а не в секундах, и это важнее, чем кажется: в
    // главном меню скриптов почти нет — замерено 57 вызовов за четыре с
    // половиной секунды, — а в игре их около полутора тысяч в секунду. Порог в
    // событиях сам отличает «висим в меню» от «играем», чего таймер не умеет.
    //
    // Первый порог — меньше минуты игры, чтобы короткий заход не остался ни с
    // чем. Остальные разнесены, чтобы поймать и начало миссии, и её середину.
    static constexpr unsigned long long kThresholds[] = {60000, 400000, 2000000};

    // Копилка объектов из потока событий.
    //
    // Прямо отображённая хеш-таблица: слот по хешу указателя, занят — проходим
    // мимо. Дедупликация за одну операцию вместо перебора всех накопленных;
    // на горячем пути это единственный приемлемый вариант. Часть объектов
    // теряется на коллизиях, и это осознанный размен: запасной список нужен
    // полным настолько, чтобы по нему было видно карту, а не поимённо весь мир.
    static constexpr std::size_t kSeenSlots = 1 << 14;

    std::atomic<const void*> seen_[kSeenSlots] = {};
    std::atomic<std::size_t> seenCount_{0};

    std::atomic<unsigned long long> events_{0};
    std::atomic<int> dumpsDone_{0};
    std::atomic<bool> busy_{false};

    // Атомарный, потому что растёт из хука, а хук зовут разные потоки игры.
    std::atomic<std::size_t> nextThreshold_{0};

    // Поток горячей клавиши. Опрашивать клавиатуру из хука нельзя: он на
    // горячем пути, и системный вызов там стоит кадров.
    std::atomic<bool> watching_{false};

    void remember(const void* object);
    void watchHotkey();

    // Снимок. reason попадает в файл и в окно, чтобы по набору файлов было
    // видно, что чем вызвано.
    void dump(const char* reason);

    void writeNames(std::FILE* file);
    void writeObjects(std::FILE* file, std::FILE* hex);
    void writeFallbackObjects(std::FILE* file, std::FILE* hex);
    void writeClasses(std::FILE* file);
};

}  // namespace dmk
