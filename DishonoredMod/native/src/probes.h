#pragma once

#include <atomic>

// Счётчики зондов.
//
// Какую именно функцию скриптовой машины нужно перехватывать, из статического
// разбора не следует однозначно: в релизе имена вырезаны, а функции с
// одинаковым прологом стоят рядом и обе уходят в ProcessInternal. Прошлый заход
// на этом и споткнулся — перехвачена была не та, и снаружи это выглядело как
// «хук стоит, событий нет», то есть неотличимо от «игра ещё не загрузилась».
//
// Поэтому теперь плагин ставит счётчик на каждого кандидата и даёт ответить
// самой игре: живой тот, у которого счётчик растёт. Одно измерение вместо
// цепочки догадок.
//
// Растут из игровых потоков, читаются из потока отчёта — отсюда atomic.

namespace dmk {

inline std::atomic<unsigned long long> g_callFunctionHits{0};
inline std::atomic<unsigned long long> g_opcodeHits{0};

}  // namespace dmk
