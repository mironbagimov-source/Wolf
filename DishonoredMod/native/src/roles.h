#pragma once

#include <cstddef>
#include <cstring>

// За кого можно играть на приёме у Бойл.
//
// Роль — это сторона. Всё остальное игра выводит из неё сама: стража
// пропускает своего, гости принимают гостя, плакальщики бросаются на того, кто
// им враг. Технически роль сводится к одной ссылке — m_pFactionTweak у твика
// пешки игрока, обычному ObjectProperty.
//
// Имена фракций здесь не придуманы: каждое прочитано из выгрузки живой карты
// приёма вместе с содержимым массивов отношений. Держит их код, а не конфиг,
// именно поэтому: имя фракции можно опечатать, и правка молча не применится, а
// выбор из списка ошибиться не даёт.
//
// Таблица вынесена в заголовок отдельно от режима, потому что расстановка
// четверых — не комментарий, а утверждение, которое можно нарушить правкой
// одной строки. Тест рядом проверяет его как утверждение: Корво с Даудом на
// одной стороне, Томас с Билли на другой, стороны разные. Патчер в тест не
// тянется — он весь на Windows API, — а таблица тянется целиком.

namespace dmk {

struct RoleDefinition {
    // Как роль пишется в конфиге.
    const char* id;

    // Объект DisTweaks_Faction на карте приёма.
    const char* faction;

    // Подстрока имени, по которой на карте ищется тело этого персонажа.
    //
    // Фракция меняет то, кем тебя считают, но не то, как ты выглядишь: тело
    // остаётся Корво. Тела Дауда, Томаса и Билли лежат в пакетах затопленного
    // района, и на приёме их, по всем признакам, нет. «По всем признакам» — не
    // ответ, поэтому режим ищет их сам и пишет в лог, что нашлось. Обход
    // списка объектов всё равно идёт, так что проверка бесплатна, а гадать
    // больше не о чем.
    //
    // Пусто у ролей приёма: их тела на карте есть по определению — гости,
    // стража и плакальщики по ней и ходят.
    const char* hint;

    const char* description;
};

// Расстановка четверых складывается сама, без единой правки таблиц отношений.
// Корво и Дауд стоят на Faction_Corvo_Default, Томас и Билли — на
// Faction_Assassin_Default. Одна фракция на двоих делает их союзниками по
// построению, а вражда между сторонами в игре уже прописана: у китобоев Корво
// первым в списке врагов. Раскол китобоев, ради которого всё затевалось,
// оказался готовым — нужно только встать на нужную сторону.
inline constexpr RoleDefinition kRoles[] = {
    // Четверо, ради которых режим и делался.
    {"corvo", "Faction_Corvo_Default", "",
     "Корво: с Даудом заодно, стража враждебна"},
    {"daud", "Faction_Corvo_Default", "Daud",
     "Дауд: раскол китобоев, он на стороне Корво, Томас и Билли — враги"},
    {"thomas", "Faction_Assassin_Default", "Assassin",
     "Томас: китобой, враг Корво с Даудом, страже и головорезам"},
    {"billie", "Faction_Assassin_Default", "Billie",
     "Билли Лерк: с Томасом заодно, против Корво и Дауда"},

    // Стороны самого приёма: за них играется мирная половина режима.
    {"guest", "Neutral_Civilian", "",
     "гость приёма: стража терпит, гости свои, плакальщики нападают"},
    {"guard", "Neutral_Guard", "",
     "стражник приёма: свой для стражи и гостей"},
    {"civilian", "Faction_Civilian_Default", "",
     "горожанин: свой всем, кроме плакальщиков"},
    {"conspiracy", "Faction_Conspiracy_Default", "",
     "заговорщик: сторона, которая наняла Корво"},
    {"weeper", "Faction_Weepers_Default", "",
     "плакальщик: враг всему живому, и живое это знает"},
};

inline constexpr std::size_t kRoleCount = sizeof(kRoles) / sizeof(kRoles[0]);

// Твики пешки игрока, найденные на карте приёма.
//
// Правятся все три, и это не перестраховка. Какой из них игра читает на самом
// деле, из выгрузки не видно, а промах выглядел бы хуже всего: лог отчитался бы
// об успешной правке, и ничего бы не изменилось. Три записи вместо одной стоят
// ничего, а вопрос снимают целиком.
inline constexpr const char* kPlayerTweaks[] = {
    "Twk_Pawn_Corvo",
    "Twk_Pawn_Corvo_Release",
    "Twk_Pawn_DefaultPlayer",
};

inline constexpr std::size_t kPlayerTweakCount =
    sizeof(kPlayerTweaks) / sizeof(kPlayerTweaks[0]);

// Роль по имени из конфига. nullptr, если такой нет.
//
// Сравнение без учёта регистра: конфиг пишет человек, и Daud вместо daud —
// не ошибка, о которой стоит сообщать.
inline const RoleDefinition* findRole(const char* id) {
    if (id == nullptr) {
        return nullptr;
    }
    for (const RoleDefinition& definition : kRoles) {
        const char* left = definition.id;
        const char* right = id;
        while (*left != '\0' && *right != '\0') {
            const char a = (*left >= 'A' && *left <= 'Z') ? *left + 32 : *left;
            const char b = (*right >= 'A' && *right <= 'Z') ? *right + 32 : *right;
            if (a != b) {
                break;
            }
            ++left;
            ++right;
        }
        if (*left == '\0' && *right == '\0') {
            return &definition;
        }
    }
    return nullptr;
}

}  // namespace dmk
