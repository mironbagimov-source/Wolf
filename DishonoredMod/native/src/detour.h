#pragma once

#include <cstdint>
#include <cstddef>
#include <vector>

#include "bytepattern.h"  // kJumpSize, encodeRelativeJump

// Перехват функции подменой её начала на JMP.
//
// Схема классическая: первые байты функции заменяются на переход к нашему
// коду, а вытесненные («украденные») байты копируются в трамплин, за которым
// ставится переход обратно в тело оригинала. Через трамплин мы вызываем
// оригинальную функцию как ни в чём не бывало.
//
// Длину украденного куска класс НЕ вычисляет сам. Полноценный подсчёт длин
// инструкций x86 — это отдельный дизассемблер на несколько сотен строк,
// который ошибается ровно там, где это дороже всего: на редкой инструкции в
// прологе конкретной функции. Здесь длина передаётся снаружи, а тот, кто её
// передаёт, обязан посмотреть пролог в дизассемблере и убедиться, что граница
// проходит по концу инструкции. Разрез посреди инструкции даёт трамплин,
// который исполняет мусор, — падение в этом случае в лучшем случае мгновенное,
// в худшем плавающее.
//
// Диапазон перехода на x86 не проверяется намеренно: относительный операнд
// 32-битный, адресное пространство тоже, поэтому переполнение при вычитании
// даёт ровно нужное смещение при любом расположении модулей.

namespace dmk {

class Detour {
public:
    Detour() = default;
    ~Detour();

    Detour(const Detour&) = delete;
    Detour& operator=(const Detour&) = delete;

    // targetAddress   — адрес перехватываемой функции;
    // replacement     — адрес нашей функции, соглашение вызова обязано
    //                   совпадать с оригиналом;
    // stolenByteCount — длина пролога, кратная целым инструкциям, не меньше 5.
    bool install(std::uintptr_t targetAddress, void* replacement, std::size_t stolenByteCount);

    // Возвращает начало функции в исходный вид.
    bool uninstall();

    bool installed() const { return installed_; }

    // Трамплин: вызов оригинальной функции. Приводится к нужному типу
    // указателя на функцию на стороне вызывающего.
    void* original() const { return trampoline_; }

private:
    std::uintptr_t target_ = 0;
    std::uint8_t* trampoline_ = nullptr;
    std::vector<std::uint8_t> originalBytes_;
    bool installed_ = false;
};

}  // namespace dmk
