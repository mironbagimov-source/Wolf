#pragma once

#include <cstdint>

// Поиск функций по сигнатуре, а не по жёстко зашитому адресу.
//
// Жёсткий адрес привязывает мод к одному-единственному экзешнику: любой патч
// или другая площадка распространения — и мод молча промахивается мимо чужого
// кода, что кончается падением без внятной причины. Сигнатура — это кусок
// машинного кода функции с замаскированными байтами, которые меняются от
// сборки к сборке (адреса в операндах). Она переживает пересборку игры.

namespace dmk {

// Диапазон исполняемой памяти модуля.
struct ModuleRange {
    std::uintptr_t base = 0;
    std::size_t size = 0;

    bool valid() const { return base != 0 && size != 0; }
};

// Границы главного модуля процесса (самого экзешника игры).
ModuleRange mainModuleRange();

// Ищет сигнатуру вида "55 8B EC ?? ?? 83 EC" — пробелы произвольны,
// "??" (или одиночный "?") означает «любой байт».
//
// Возвращает адрес первого совпадения либо 0. Если совпадений больше одного,
// это повод переписать сигнатуру: неоднозначная сигнатура рано или поздно
// поймает не ту функцию.
std::uintptr_t findPattern(const ModuleRange& range, const char* pattern);

// Сколько раз сигнатура встречается. Нужно ровно для проверки на
// неоднозначность при подборе новой сигнатуры.
std::size_t countPattern(const ModuleRange& range, const char* pattern);

}  // namespace dmk
