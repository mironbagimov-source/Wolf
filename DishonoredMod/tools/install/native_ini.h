#pragma once

// Содержимое native.ini, вшитое в установщик.
//
// Отдельным файлом конфиг оказался лишним поводом для поломки: Windows
// дописывает расширение при скачивании, мессенджеры добавляют суффиксы, и
// установщик честно не находит «native.ini», хотя рядом лежит
// «native.ini.txt». Файл, которого не нужно, потерять нельзя.
//
// Файл рядом с установщиком по-прежнему главнее: если он есть, ставится он.
// Этот текст — запасной вариант, и он же гарантирует, что версия конфига
// всегда сходится с версией установщика.
//
// Сгенерировано из native/native.ini скриптом tools/install/embed_ini.py —
// править надо там, а не здесь.

namespace dmk {

inline const char* kEmbeddedNativeIni = R"DMKINI(; Настройки нативного слоя. Кладётся рядом с dinput8.dll в папке игры.
;
; Все адреса и сигнатуры задаются здесь, а не только в коде: их подбор — работа
; итеративная, и пересобирать DLL на каждую попытку незачем. Копии тех же
; значений вшиты в DLL, поэтому потерянный файл ничего не ломает.

[General]
; Версия формата конфига. Не трогай: по ней плагин понимает, что файл рядом с
; ним — от текущей версии мода, а не остался от предыдущей.
;
; Если версия старая или ключа нет вовсе, плагин игнорирует секции с
; сигнатурами целиком и берёт вшитые в себя значения. Иначе достаточно
; заменить одну DLL, забыв про этот файл, — и старые настройки тихо отключат
; перехват.
ConfigVersion=4

; Показывать окна с ходом работы. На этапе настройки — обязательно: окно видно
; сразу и целиком, а лог в папке игры ещё надо найти и открыть.
ShowLoadMessage=1

; Куда писать лог. Укажи любую свою папку — она пробуется первой, и лог не
; придётся искать. Папка создаётся, если её нет.
;
; Если оставить пустым или ошибиться в пути, лог уйдёт в запасные места:
; рядом с плагином, потом в %LOCALAPPDATA%\DishonoredModKit, потом во
; временную папку. Путь пишется первой строкой самого лога и в окне.
;
; Пример: LogPath=C:\килька
LogPath=

; Активный режим: observer, dump или roleplay.
;
;   observer — только считает вызовы, ничего не меняет
;   dump     — выписывает имя каждой вызванной функции в
;              DishonoredModKit-names.txt рядом с логом
;   roleplay — ролевой режим
;
; dump нужен один раз: он снимает необходимость угадывать имена событий.
; Пройди уровень с ним, посмотри файл — там будут и разговоры, и смерти.
Mode=dump

; Ставить ли хуки. 0 — плагин грузится и пишет лог, но в чужой код не лезет.
HookEnabled=1

[CallFunction]
; UObject::CallFunction — основной источник событий. Описание вызываемой
; функции приходит третьим аргументом, поэтому имя события читается сразу.
;
; Опознана по тому, что из третьего аргумента читаются FunctionFlags (+0x80)
; с проверкой бита FUNC_Native 0x400 и iNative (+0x84) — так делает только она.
; Оттуда же идёт один из двух прямых вызовов ProcessInternal. Адрес 0x00470230
; в розничной сборке 1.0.
Pattern=55 8B EC 6A FF 68 ?? ?? ?? ?? 64 A1 ?? ?? ?? ?? 50 83 EC 58 A1 ?? ?? ?? ?? 33 C5 89 45 F0 53 56

; Длина пролога в байтах — сколько байт вытесняется переходом.
; Здесь ровно 5 и граница попадает точно на конец инструкции:
;   55       push ebp        (1 байт)
;   8B EC    mov ebp, esp    (2 байта)
;   6A FF    push -1         (2 байта)
PrologueBytes=5

[OpcodeHandler]
; Обработчик опкода скриптовой машины — 0x0046F8D0. Только счётчик: описания
; функции у него в аргументах нет, поэтому имена отсюда не берутся.
;
; Нужен, чтобы отличить «скрипты не исполняются вовсе» от «исполняются, но не
; через CallFunction»: снаружи оба состояния выглядят одинаково — пустой лог.
; Эта функция раньше была принята за ProcessEvent, и ошибка вскрылась только
; счётчиком: за двадцать секунд игры ноль вызовов, чего с ProcessEvent быть не
; может.
Pattern=55 8B EC 6A FF 68 ?? ?? ?? ?? 64 A1 ?? ?? ?? ?? 50 83 EC 70 A1 ?? ?? ?? ?? 33 C5 89 45 F0 53 56 57 50 8D 45 F4 64 A3 00 00 00 00 89
PrologueBytes=5

[Names]
; Глобальная таблица имён UE3. Без неё режимы видят поток вызовов, но не могут
; отличить разговор от шага: имена хранятся индексами, а не строками.
; Подробности — в src/ue3names.h.

; Значения снял автоподбор на розничной сборке 1.0 и подтвердил прочитанными
; именами: GetOnlineSubsystem, AddLoginChangeDelegate, NotEqual_InterfaceInterface —
; это UnrealScript, ни с чем не спутать.
;
; Та же раскладка вшита в DLL, так что нули здесь ничего не ломают: плагин
; возьмёт вшитую. В любом случае она проверяется на живых объектах, и если
; сборка игры другая — подбор запустится сам.
;
; Статически эти адреса не берутся: на диске глобалы нулевые, таблица
; заполняется только в рантайме.

; Адрес TArray<FNameEntry*>. Принимается и десятичный, и шестнадцатеричный
; (с префиксом 0x) вид.
GNamesAddress=0x01435674

; Смещение поля FName внутри UObject.
ObjectNameOffset=40

; Смещение начала строки внутри FNameEntry.
EntryStringOffset=16

; Хранятся ли имена в широких символах: 1 — да, 0 — однобайтовые.
EntryIsWide=0

[Roleplay]
; Фракция выбирается разговором с гостем на приёме у Бойл. Первый разговор
; запирает выбор.
;
; Порядок настройки такой. Сначала оставь ConversationEvent пустым и задай
; DiscoveryFilter — режим будет писать в лог каждое новое имя события,
; содержащее эту подстроку. Зайди на карту, заговори с гостем, посмотри лог:
; нужное имя окажется там. Впиши его в ConversationEvent — и режим заработает.
;
; Имя события угадать нельзя, его можно только подсмотреть в живой игре,
; поэтому разведка — обязательный первый шаг, а не запасной вариант.

; Подстрока для разведки. Разумные кандидаты: Convo, Talk, Dialog, Speak.
DiscoveryFilter=Convo

; Имя события разговора. Пока пусто — режим только разведывает.
ConversationEvent=

; Смещение номера фракции внутри объекта NPC. Ищется через консольную команду
; GetAll с именем класса и свойства Team.
TeamOffset=0

; Запирать ли выбор после первого разговора: 1 — да.
LockAfterFirst=1
)DMKINI";

}  // namespace dmk
